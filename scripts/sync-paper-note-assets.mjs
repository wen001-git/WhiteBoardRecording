import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const markerStart = '// PAPER_NOTE_ASSETS_START — generated by scripts/sync-paper-note-assets.mjs';
const markerEnd = '// PAPER_NOTE_ASSETS_END';
const assets = [
  { name: '纸张便签·暖白横版', file: 'warm-white-horizontal.webp', width: 480, height: 312 },
  { name: '纸张便签·米黄横版', file: 'warm-beige-horizontal.webp', width: 480, height: 281 },
  { name: '纸张便签·浅灰横版', file: 'cool-gray-horizontal.webp', width: 480, height: 237 },
  { name: '纸张便签·暖白竖版', file: 'warm-white-vertical.webp', width: 342, height: 480 },
  { name: '纸张便签·米黄竖版', file: 'warm-beige-vertical.webp', width: 333, height: 480 },
  { name: '纸张便签·浅灰竖版', file: 'cool-gray-vertical.webp', width: 370, height: 480 },
];

function quotedChunks(base64) {
  return base64.match(/.{1,120}/g).map((chunk) => `'${chunk}'`).join('+\n        ');
}

async function generatedBlock() {
  const entries = [];
  for (const asset of assets) {
    const bytes = await readFile(resolve(root, 'assets/stickers/paper-notes', asset.file));
    const base64 = quotedChunks(bytes.toString('base64'));
    entries.push(
      `  {name:'${asset.name}',kind:'paperNote',w:${asset.width},h:${asset.height},src:'data:image/webp;base64,'+\n        ${base64}}`,
    );
  }
  return `${markerStart}\nconst PAPER_NOTE_STICKERS = [\n${entries.join(',\n')}\n];\n${markerEnd}`;
}

const block = await generatedBlock();
for (const file of ['whiteboard.html', 'whiteboard-pro.html']) {
  const path = resolve(root, file);
  const source = await readFile(path, 'utf8');
  const start = source.indexOf(markerStart);
  const end = source.indexOf(markerEnd, start);
  if (start < 0 || end < 0) throw new Error(`${file}: paper-note asset markers are missing`);
  const next = source.slice(0, start) + block + source.slice(end + markerEnd.length);
  await writeFile(path, next);
  console.log(`Synced paper-note assets into ${file}`);
}
